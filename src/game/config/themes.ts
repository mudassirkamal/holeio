export type Weighted<T> = readonly (readonly [T, number])[];

export interface ThemeLighting {
  sunColor: string;
  sunIntensity: number;
  /** Sun elevation above the horizon, degrees. */
  sunElevation: number;
  /** Sun azimuth, degrees (0 = +Z). */
  sunAzimuth: number;
  hemiSky: string;
  hemiGround: string;
  hemiIntensity: number;
  skyTop: string;
  skyHorizon: string;
  skyBottom: string;
  fogColor: string;
  fogDensity: number;
  exposure: number;
  /** 0 = broad daylight, 1 = full night (lit windows, glowing lamps). */
  night: number;
  bloom: number;
  envIntensity: number;
}

export interface ThemePalette {
  grass: string;
  grassAlt: string;
  asphalt: string;
  sidewalk: string;
  curb: string;
  laneLine: string;
  centerLine: string;
  plaza: string;
  dirt: string;
  sand: string;
  outer: string;
  water: string;
  buildingTints: readonly string[];
  roofTints: readonly string[];
  carTints: readonly string[];
  clothTints: readonly string[];
  foliage: readonly string[];
  accent: readonly string[];
}

export type BorderStyleId = "barrier" | "picket" | "laser" | "logs" | "rope" | "stone";

export interface ThemeDef {
  id: ThemeId;
  name: string;
  tagline: string;
  /** Emoji and gradient shown in map pickers. */
  icon: string;
  gradient: readonly [string, string];
  /**
   * Map shape: blocks along X and Z as multiples of the chosen map size.
   * [1, 1] is a square city, [2, 0.6] a long strip with about the same area.
   */
  shape: readonly [number, number];
  /** Average block size in meters (default 44); bigger blocks fit bigger landmarks. */
  blockSize?: number;
  /** Fence style around the map. */
  border: BorderStyleId;
  /** Snow on roofs, trees and fences. */
  snowy?: boolean;
  /** Glowing trim on buildings. */
  neon?: boolean;
  /** Trees standing outside the fence, or null for none. */
  scenery: { kind: ObjectKindId; count: number } | null;
  zones: Weighted<ZoneType>;
  centerZones: Weighted<ZoneType>;
  streetTree: ObjectKindId | null;
  parkTree: ObjectKindId;
  /** Buildings on residential lots (default: houses). */
  homes?: readonly ObjectKindId[];
  /** Buildings on commercial lots (default: shops, apartments, gas stations). */
  shops?: readonly ObjectKindId[];
  /** Traffic lights at the street corners (default: yes). */
  trafficLights?: boolean;
  streetProps: Weighted<ObjectKindId>;
  parkProps: Weighted<ObjectKindId>;
  vehicles: Weighted<ObjectKindId>;
  /** Moving cars per road segment. */
  trafficDensity: number;
  /** Walkers per city block. */
  walkerDensity: number;
  outer: "grass" | "water" | "snow";
  weather: "none" | "snow" | "fireflies" | "leaves";
  /** Overrides the weather particles' color (pink petals, orange embers). */
  weatherColor?: string;
  palette: ThemePalette;
  lighting: ThemeLighting;
}

